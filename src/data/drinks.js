/**
 * 价格展示文案。
 * 三态处理，绝不显示 ¥0 或空白：
 *  - 官方价    → ¥lo–hi
 *  - 第三方价  → ¥lo–hi，并显式标注「第三方参考」（不冒充官方价）
 *  - 未公示    → 「参考价未公示」
 */
export const drinkPriceLabel = (drink) => {
  if (drink.priceStatus === 'unpublished' || !Array.isArray(drink.priceRange)) {
    return '参考价未公示'
  }
  const [lo, hi] = drink.priceRange
  const range = lo === hi ? `¥${lo}` : `¥${lo}–${hi}`
  return drink.priceStatus === 'thirdParty' ? `${range}（第三方参考）` : range
}

/**
 * 预算匹配。
 * 关键约束：价格未公示的饮品**不参与匹配**。用户选了预算档却抽到价格不明的饮品，
 * 等于给出了无法兑现的承诺，因此宁可排除、并在零候选时提示这一点。
 */
export const matchDrinkBudget = (drink, budget) => {
  if (!budget || budget.key === 'any') return true
  if (drink.priceStatus === 'unpublished' || !Array.isArray(drink.priceRange)) return false
  const [lo, hi] = drink.priceRange
  // 区间与预算档有交集即视为匹配（宽松但可解释）
  return hi > budget.min && lo < budget.max
}

/** 汇总标签，用于卡片展示 */
export const drinkTags = (drink) => {
  const tags = []
  if (drink.category) tags.push(drink.category)
  if (drink.caffeine && drink.caffeine !== 'unknown') tags.push(drink.caffeine)
  if (drink.priceStatus === 'thirdParty') tags.push('第三方参考价')
  if (drink.priceStatus === 'unpublished') tags.push('价格未公示')
  if (drink.availability === 'seasonal') tags.push('季节限定')
  if (drink.availability === 'regional') tags.push('区域限定')
  if (drink.availability === 'unknown') tags.push('在售待确认')
  return tags
}
