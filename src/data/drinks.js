/**
 * 饮品数据层（品牌 + SKU 双层结构）
 * ==================================================================
 * 设计原则（对应需求文档的「商品真实性」要求）：
 *
 * 1. 一条记录 = 某品牌的某一款具体饮品。杯型 / 温度 / 糖度是可选规格，
 *    不单独拆成条目。不同品牌的同名饮品是不同条目。
 * 2. id 统一 `drink-<品牌缩写>-<饮品缩写>`，与食物 id 永不冲突，
 *    本地收藏/历史据此区分来源。无官方商品编号时使用本应用 id，
 *    不冒充品牌官方 SKU 编码。
 * 3. 品牌信息集中在 brands.js，本表只存 brandId，避免重复维护品牌名。
 * 4. 缺失信息用 null / 空数组 / 'unknown' 表示，**绝不用 0 元或默认「无咖啡因」冒充**。
 * 5. 不推算热量、糖含量、咖啡因毫克数等营养结论。
 * 6. 价格为人民币元，且必须记录来源地区、杯型与核验日期。
 *    官方不公示价格时用 priceStatus:'unpublished' + priceRange:null。
 *
 * 核验状态说明：
 *  本文件的每一条数据都需人工核对官方菜单后录入。凡是无法核实的字段，
 *  一律留空或标 unknown，不做推测性填充。
 */

