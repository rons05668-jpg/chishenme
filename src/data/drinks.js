const norm = (value) => (value === undefined ? null : value)

/** 把原始记录补齐为结构完整的对象，缺失字段统一为 null / 空数组 */
const enrichDrink = (drink) =>
  Object.freeze({
    id: drink.id,
    brandId: drink.brandId,
    name: drink.name,
    nameTranslated: Boolean(drink.nameTranslated),
    aliases: Array.isArray(drink.aliases) ? [...drink.aliases] : [],
    category: drink.category,
    priceStatus: drink.priceStatus || 'unpublished',
    priceRange: Array.isArray(drink.priceRange) ? [...drink.priceRange] : null,
    priceNote: norm(drink.priceNote),
    priceSource: norm(drink.priceSource),
    availability: drink.availability || 'unknown',
    availabilityNote: norm(drink.availabilityNote),
    temperatures: Array.isArray(drink.temperatures) ? [...drink.temperatures] : [],
    sweetness: Array.isArray(drink.sweetness) ? [...drink.sweetness] : [],
    ingredientTags: Array.isArray(drink.ingredientTags) ? [...drink.ingredientTags] : [],
    caffeine: drink.caffeine || 'unknown',
    caffeineNote: norm(drink.caffeineNote),
    scenes: Array.isArray(drink.scenes) ? [...drink.scenes] : [],
    sources: Array.isArray(drink.sources) ? [...drink.sources] : [],
    verifiedAt: norm(drink.verifiedAt),
    desc: norm(drink.desc),
  })

export const DRINKS = DRINKS_RAW.map(enrichDrink)

export const DRINK_MAP = DRINKS.reduce((acc, drink) => {
  acc[drink.id] = drink
  return acc
}, {})

export const getDrinkById = (id) => DRINK_MAP[id] || null

/** 某品牌的全部饮品 */
export const drinksOfBrand = (brandId) => DRINKS.filter((drink) => drink.brandId === brandId)

